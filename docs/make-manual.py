def renum(text, mapping):
    """แทนที่โทเคน N.M ทีเดียวด้วยตัวยึด กันการแทนซ้อน"""
    ph = {}
    def to_ph(m):
        key = m.group(0)
        if key not in mapping: return key
        tok = f'\x00{len(ph)}\x00'
        ph[tok] = mapping[key]
        return tok
    text = re.sub(r'(?<![\d.])\d+\.\d+(?![\d])', to_ph, text)
    for tok, val in ph.items():
        text = text.replace(tok, val)
    return text

