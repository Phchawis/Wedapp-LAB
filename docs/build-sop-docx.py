FONT = '<w:rFonts w:ascii="TH SarabunPSK" w:hAnsi="TH SarabunPSK" w:cs="TH SarabunPSK" w:hint="cs"/>'
FONT_P = '<w:rFonts w:ascii="TH SarabunPSK" w:hAnsi="TH SarabunPSK" w:cs="TH SarabunPSK"/>'
COLOR = '<w:color w:val="000000" w:themeColor="text1"/>'

def esc(s):
    return html.escape(str(s), quote=False)

def rpr(bold=False, sz=32, para=False):
    f = FONT_P if para else FONT
    b = '<w:b/><w:bCs/>' if bold else ''
    cs = '' if para else '<w:cs/>'
    return f'<w:rPr>{f}{b}{COLOR}<w:sz w:val="{sz}"/><w:szCs w:val="{sz}"/>{cs}</w:rPr>'

def run(text, bold=False, sz=32):
    return f'<w:r>{rpr(bold, sz)}<w:t xml:space="preserve">{esc(text)}</w:t></w:r>'

SPACING = '<w:spacing w:before="100" w:beforeAutospacing="1" w:after="100" w:afterAutospacing="1"/>'
TIGHT = '<w:spacing w:before="0" w:after="0" w:line="240" w:lineRule="auto"/>'

def p(text='', bold=False, sz=32, ind=None, hang=None, style=None,
      num=None, align=None, spacing='auto', jc=None):
    pr = ['<w:pPr>']
    if style: pr.append(f'<w:pStyle w:val="{style}"/>')
    if num is not None:
        pr.append(f'<w:numPr><w:ilvl w:val="0"/><w:numId w:val="{num}"/></w:numPr>')
    if spacing == 'auto': pr.append(SPACING)
    elif spacing == 'tight': pr.append(TIGHT)
    if ind is not None:
        h = f' w:hanging="{hang}"' if hang else ''
        pr.append(f'<w:ind w:left="{ind}"{h}/>')
    if align: pr.append(f'<w:jc w:val="{align}"/>')
    pr.append(rpr(bold, sz, para=True).replace('<w:rPr>', '<w:rPr>').replace('<w:cs/>', ''))
    pr.append('</w:pPr>')
    body = run(text, bold, sz) if text != '' else ''
    return '<w:p>' + ''.join(pr) + body + '</w:p>'

def pagebreak():
    return ('<w:p><w:pPr>' + TIGHT + '</w:pPr><w:r><w:br w:type="page"/></w:r></w:p>')

def cell(text, w, bold=False, sz=28, shade=None, align=None, valign='center'):
    sh = f'<w:shd w:val="clear" w:color="auto" w:fill="{shade}"/>' if shade else ''
    va = f'<w:vAlign w:val="{valign}"/>'
    lines = text.split('\n') if text else ['']
    ps = ''.join(
        '<w:p><w:pPr>' + TIGHT +
        (f'<w:jc w:val="{align}"/>' if align else '') +
        rpr(bold, sz, para=True) + '</w:pPr>' +
        (run(l, bold, sz) if l else '') + '</w:p>'
        for l in lines)
    return (f'<w:tc><w:tcPr><w:tcW w:w="{w}" w:type="dxa"/>{sh}{va}'
            f'<w:tcMar><w:top w:w="40" w:type="dxa"/><w:bottom w:w="40" w:type="dxa"/></w:tcMar>'
            f'</w:tcPr>{ps}</w:tc>')

def table(rows, widths, header=True, sz=28, aligns=None):
    total = sum(widths)
    grid = ''.join(f'<w:gridCol w:w="{w}"/>' for w in widths)
    out = [f'<w:tbl><w:tblPr><w:tblStyle w:val="TableGrid"/>'
           f'<w:tblW w:w="{total}" w:type="dxa"/>'
           f'<w:tblLook w:val="04A0" w:firstRow="1" w:lastRow="0" w:firstColumn="1"'
           f' w:lastColumn="0" w:noHBand="0" w:noVBand="1"/></w:tblPr>'
           f'<w:tblGrid>{grid}</w:tblGrid>']
    for i, r in enumerate(rows):
        hd = (i == 0 and header)
        trpr = '<w:trPr><w:tblHeader/></w:trPr>' if hd else ''
        cells = ''.join(
            cell(c, widths[j], bold=hd, sz=sz,
                 shade='EDEDED' if hd else None,
                 align=(aligns[j] if aligns and not hd else ('center' if hd else None)))
            for j, c in enumerate(r))
        out.append(f'<w:tr>{trpr}{cells}</w:tr>')
    out.append('</w:tbl>')
    # ย่อหน้าว่างคั่นหลังตาราง กัน Word เอาตารางติดกัน
    out.append('<w:p><w:pPr>' + TIGHT + '</w:pPr></w:p>')
    return ''.join(out)

